"""Controlled finite-step geometry experiment for a rank-one linear SDE.

The experiment separates three claims that are easy to conflate:

1. Exact finite-step covariance propagates instantaneous noise through drift.
2. An Euler solver with multiple substeps converges to that geometry; a single
   Euler step has only the instantaneous diffusion support.
3. An analytic support/chi-square audit can be size-distorted when it uses the
   wrong geometry, whereas a fitted-null Monte Carlo rank of the same raw
   instantaneous-orthogonal score remains calibrated.

The model is the stable two-dimensional linear SDE

    dX_1 = (-alpha X_1 + kappa X_2) dt
    dX_2 = -beta X_2 dt + sigma dW.

Noise is injected only into X_2.  For kappa != 0, drift propagates it into X_1
over every positive observation interval, making the exact transition
covariance full rank.  The kappa=0 case is an invariant-support negative
control: support remains rank one, although finite-step scale still differs
from h G G^T when beta != 0.

Outputs are written below cache/summaries/finite_step_geometry_synthetic/.
"""

